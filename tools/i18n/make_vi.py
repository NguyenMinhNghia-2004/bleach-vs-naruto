def build(zh):
    missing = []

    def walk(o, path):
        if isinstance(o, dict):
            return {k: walk(v, path + [k]) for k, v in o.items()}
        key = '.'.join(path)
        if key in EXTRA:
            return EXTRA[key]
        if key not in VI:
            missing.append(key)
            return o
        return VI[key]

    out = walk(zh, [])
    for key, val in EXTRA.items():
        node = out
        parts = key.split('.')
        for p in parts[:-1]:
            node = node.setdefault(p, {})
        node[parts[-1]] = val
    return out, missing


def main():
    with open(os.path.join(ROOT, 'zh-CN.json'), encoding='utf-8') as f:
        zh = json.load(f)
    vi, missing = build(zh)
    if missing:
        print('missing translations:', missing)
        sys.exit(1)
    with open(os.path.join(ROOT, 'vi.json'), 'w', encoding='utf-8') as f:
        json.dump(vi, f, ensure_ascii=False, indent=2)
    # the online-lobby keys must also exist for the other languages (fallback text)
    for lang in ('zh-CN',):
        p = os.path.join(ROOT, lang + '.json')
        with open(p, encoding='utf-8') as f:
            d = json.load(f)
        d.setdefault('txt', {})['online'] = dict(ZH_ONLINE)
        with open(p, 'w', encoding='utf-8') as f:
            json.dump(d, f, ensure_ascii=False, indent=2)
    print('vi.json written,', len(VI) + len(EXTRA), 'strings')


if __name__ == '__main__':
    main()
